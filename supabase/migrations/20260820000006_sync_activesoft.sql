-- ---------------------------------------------- 1. a data de nascimento
-- Estava nula para os 505. Ela decide a faixa do questionario dos pais, e aos 2
-- anos a idade em meses vale mais que a serie.
update public.profiles p
   set data_nascimento = a.nascimento
  from as_alunos a
 where p.matricula_externa = a.matricula
   and p.data_nascimento is distinct from a.nascimento;

-- ------------------------------------------- 2. quem saiu sai da turma
-- Desativa o vinculo. O perfil, as observacoes e as entregas ficam.
update public.aluno_turma at
   set ativo = false,
       data_saida = coalesce(at.data_saida, current_date),
       motivo_saida = coalesce(at.motivo_saida, 'Sem matricula ativa no ActiveSoft em 20/08/2026')
  from public.profiles p
 where at.aluno_id = p.id
   and at.ativo
   and at.ano_letivo = 2026
   and p.matricula_externa is not null
   and not exists (select 1 from as_alunos a where a.matricula = p.matricula_externa);

select 'nascimentos preenchidos' as passo,
       (select count(*) from public.profiles where data_nascimento is not null) as total
union all
select 'vinculos desativados agora',
       (select count(*) from public.aluno_turma
         where not ativo and motivo_saida like '%ActiveSoft%');
